// Regenerates src/sprites_gen.rs from the extracted JS core (run after sprite changes).
import * as core from '../../lang/fc-core.mjs';
import fs from 'fs';
// SPRITES isn't exported; re-read it via the module source (evaluated copy not needed —
// parse the hex via a tiny eval of the table region would be fragile; instead use the
// exported drawSprite? Not exported either. So: regex the source.)
const src = fs.readFileSync(new URL('../../lang/fc-core.mjs', import.meta.url), 'utf8');
const start = src.indexOf('const SPRITES = {');
const end = src.indexOf('\n};', start);
const body = src.slice(start, end);
const sprites = {};
// entries: name: spr('row',...8) — capture name + 8 quoted rows
const re = /([\w ]+|'[\w ]+'):\s*spr\(([^)]+)\)/g;
let m;
while ((m = re.exec(body))) {
  const name = m[1].replace(/'/g, '').trim();
  const rows = [...m[2].matchAll(/'([0-9a-fA-F]{8})'/g)].map(x => x[1]);
  if (rows.length === 8) sprites[name] = rows.join('');
}
// aliases like "hero: SPRITES.hero_down"? handle `name: <ident>` references
const re2 = /(\w+):\s*spr_alias\(/g; // none expected; aliases handled below
const aliasRe = /'?([\w ]+)'?:\s*SPRITES\.(\w+)/g;
while ((m = aliasRe.exec(body))) { if (sprites[m[2]]) sprites[m[1].trim()] = sprites[m[2]]; }
const palStart = src.indexOf('const SPRITE_PAL = [');
const palEnd = src.indexOf('];', palStart);
const pal = [...src.slice(palStart, palEnd).matchAll(/'(#[0-9a-fA-F]{6})'/g)].map(x => x[1]);
let out = '// GENERATED by gen-sprites.mjs from spec/lang/fc-core.mjs — do not hand-edit.\n';
out += 'pub const SPRITE_PAL: [&str; ' + (pal.length + 1) + '] = ["", ' + pal.map(c => '"' + c + '"').join(', ') + '];\n';
const names = Object.keys(sprites).sort();
out += 'pub const SPRITES: [(&str, &str); ' + names.length + '] = [\n';
for (const n of names) out += '    ("' + n + '", "' + sprites[n] + '"),\n';
out += '];\n';
fs.writeFileSync('src/sprites_gen.rs', out);
console.log('wrote src/sprites_gen.rs:', names.length, 'sprites,', pal.length, 'palette colors');
console.log('has:', ['hero','brick','coin','ghost'].map(n=>n+':'+!!sprites[n]).join(' '));
